import type { WeekShopping } from './types'

function items(
  rows: Array<[string, string, string]>,
): WeekShopping['items'] {
  return rows.map(([name, weeklyTotal, buy], i) => ({
    id: `${name.toLowerCase().replace(/\s+/g, '-')}-${i}`,
    name,
    weeklyTotal,
    buy,
  }))
}

